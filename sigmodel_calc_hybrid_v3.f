	subroutine sigmodel_calc(e1pass,e2pass,thpass,zpass,apass,mpass,sig_dis_pass,sig_qe_pass,sig,xflag,factpass)
C       +______________________________________________________________________________
c	
C       Calculate cross section using Peter's F1F209.f routine
c       
c       ARGUMENTS:
c       
c       E1:		-	Incident energy in GeV.
c       E2:		- Scattered energy in GeV.
c       TH:		- Scattering angle in Degrees.
c       A:		- 'A' of nucleus.
c       Z:		- Number of protons in nucleus.
c       M_TGT:	- Mass of target nucleus in GeV/c2.
c       M_REC:	- Mass of recoiling nucleon in GeV/c2.
c       E_SEP:	- Separation energy for target nucleus in GeV/c2.
c       SIG  :	- Calculated cross section in nb/(MeV-ster).
C       ______________________________________________________________________________

        implicit none
	include 'math_physics.inc'
	include 'include.inc'

C       Declare arguments.

	real*8		e1,e2,th,a,z,m_tgt,atmp,ztmp
	real*4          e1pass,e2pass,thpass,mpass
	real*4          sig,factpass,sig_dis_pass,sig_qe_pass
	real*4          x4,A4,fitemc_rock
	integer         zpass,apass
	logical		modelhack

C       Declare locals.

	real*8	 	sig_qe,sig_dis,y,normfac,fact
        real*8		thr,cs,sn,tn,elastic_peak
	real*8          Q2,nu,WSQ, x
	real*8          w2qe,q2qe
	real*8          W1p,W2p,W1n,W2n,W1D,W2D,W1ineft,W2ineft,W1smear,W2smear
	real*8          F1,F2,FL,W1,W2,sigmott,r,frac
	real*8          inelastic_it,emcfit_e139,jra_nprat,f2rat,isocor,emcfit_xem2
	integer         xflag	!flag for which xsec to calculate 1=both 2=QE only 3=DIS only
	integer         wfn
	logical         first,goodfit,firstf1f2


	save

        real*8 emc_func_xem
	external emc_func_xem

	real*8 emc_func_slac
	external emc_func_slac

	data first/.true./

	data firstf1f2/.TRUE./
c needed by f1f2in21
	if(firstf1f2) then
	   write(6,*) 'Initializing F1F2IN21:'  
	   write(6,*) 'F1F2IN21: calling sqesub'
	   q2qe=1.
	   w2qe=1.
	   wfn=2
	   call sqesub(w2qe,q2qe,wfn,f1,f2,fL,firstf1f2)
	   firstf1f2=.false.
	endif
	
	e1=dble(e1pass)
	e2=dble(e2pass)
	th=dble(thpass)
	a=dble(apass)
	z=dble(zpass)
	m_tgt=dble(mpass)


	sig =0.0
	sig_qe=0.0
	sig_dis=0.0

C       If at or beyond elastic peak, return ZERO!

	thr = th*d_r
	cs = cos(thr/2.)
	sn = sin(thr/2.)
	tn = tan(thr/2.)
	elastic_peak = e1/(1.+2.*e1*sn**2/m_tgt)
      	if (e2.ge.elastic_peak) then
       	   sig = 0.0
       	   return
       	endif
c	write(6,*) 'got to 1'

	Q2 = 4.*e1*e2*sn**2
	nu=e1-e2
	WSQ = -Q2 + m_p**2 + 2.0*m_p*nu 
        x = Q2/2/m_p/nu

	x4=x
	A4=A

	F1=0
	F2=0
	r=0
	sig_dis=0.0
	sig_qe=0.0
	if((xflag.eq.1).or.(xflag.eq.3)) then
c----------------------------------------------------------------
c       
c       do inelastic stuff - use F1F2IN21
	   W1=0.0
	   W2=0.0
	   Atmp=min(2.0,A)
	   Ztmp=1.0d0
	   call F1F2IN21(Ztmp, Atmp, Q2, WSQ, F1, F2)
	   W1 = F1/m_p
	   W2 = F2/nu
C       Mott cross section	      
	   sigmott=(19732.0/(2.0*137.0388*e1*sn**2))**2*cs**2/1.d6
	   sig_dis = 1d3*sigmott*(W2+2.0*W1*tn**2) ! this should be nb/GeV/sr
c	   sig_dis=sig_dis*inelastic_it(x,Atmp,Ztmp) ! apply correction to deuterium here
	   if(A.gt.2.0) then
	      f2rat=jra_nprat(x,Q2)
	      isocor=0.5*A*(1.0+f2rat)/(Z+(A-Z)*f2rat)
	      sig_dis=sig_dis*(A/2.0)*emcfit_xem2(x,A)/isocor !emcfit_e139(x,A)/isocor
	   endif
c	   sig_dis=sig_dis*inelastic_it(x,A,Z)
	endif

	if((xflag.eq.1).or.(xflag.eq.2)) then
	   F1=0.0
	   F2=0.0
	   W1=0.0
	   W2=0.0
	   if(A.gt.2.0) then
	      call F1F2QE09(Z, A, Q2, WSQ, F1, F2)
	   else
	      call F1F2QE21(Z, A, Q2, WSQ, F1, F2)
	   endif
C       Convert F1,F2 to W1,W2
	   W1 = F1/m_p
	   W2 = F2/nu
C       Mott cross section
	   sigmott=(19732.0/(2.0*137.0388*e1*sn**2))**2*cs**2/1.d6
	   sig_qe = 1d3*sigmott*(W2+2.0*W1*tn**2)
	endif


	sig = sig_qe + sig_dis	!sig is already real*4


	sig_qe_pass = sig_qe ! pass back as real*4
	sig_dis_pass = sig_dis

	return
	end


